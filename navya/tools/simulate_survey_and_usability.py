#!/usr/bin/env python3
"""Generates the SIMULATED survey (60 respondents) and usability session (5 participants) for Navya.

These numbers are invented for the course, with the mentor's approval, the same way as in the FestPass project.
They are not evidence that real people want Navya. Replace them with real responses before using them in a pitch.
The random seed is fixed, so running this again gives the same files.
  python3 simulate_survey_and_usability.py
"""
import csv, pathlib, random, statistics as st

OUT = pathlib.Path(__file__).resolve().parents[2] / "navya-docs" / "1-Startup-Policies" / "research-evidence"

rnd = random.Random(2026)
CITIES = ["Pune", "Mumbai", "Bengaluru", "Delhi", "Chennai", "Hyderabad"]
CITY_W = [26, 20, 18, 14, 12, 10]
PLATFORMS = ["OLX", "Instagram", "WhatsApp groups", "Facebook Marketplace", "Vinted-style app", "None"]
PROBLEMS = ["Scams and fake listings", "Low or no offers", "Poor photos or details", "Sharing my phone number", "Hard to find things nearby", "Bargaining takes too long"]
PROB_W = [26, 18, 14, 16, 14, 12]

rows = []
for i in range(1, 61):
    sold = rnd.random() < 0.62
    bought = rnd.random() < 0.55
    plat = rnd.choices(PLATFORMS, [28, 30, 22, 8, 4, 8])[0] if (sold or bought) else "None"
    interest = min(5, max(1, round(rnd.gauss(3.7, 0.9))))
    safety = min(5, max(1, round(rnd.gauss(4.0, 0.8))))
    boost = rnd.choices(["Yes", "Maybe", "No"], [22, 38, 40])[0]
    maxfee = 0 if boost == "No" else rnd.choice([20, 29, 49, 49, 49, 79, 99]) if boost == "Yes" else rnd.choice([0, 20, 29, 49])
    rows.append({
        "id": i, "city": rnd.choices(CITIES, CITY_W)[0], "age": rnd.choice([18, 19, 19, 20, 20, 21, 21, 22, 23, 24]),
        "sold_online_before": "Yes" if sold else "No", "bought_secondhand_before": "Yes" if bought else "No", "main_platform": plat,
        "biggest_problem": rnd.choices(PROBLEMS, PROB_W)[0], "interest_1to5": interest, "safety_concern_1to5": safety,
        "would_pay_to_boost": boost, "max_fee_rupees": maxfee, "items_to_sell": rnd.choice([0, 1, 2, 3, 4, 5, 6, 8, 10]),
    })
with open(OUT / "survey-responses.csv", "w", newline="") as f:
    w = csv.DictWriter(f, fieldnames=list(rows[0])); w.writeheader(); w.writerows(rows)

def pct(n): return f"{100*n/len(rows):.0f}%"
def count(k, v): return sum(1 for r in rows if r[k] == v)
pay = [r["max_fee_rupees"] for r in rows if r["would_pay_to_boost"] in ("Yes", "Maybe")]
out = ["# Survey summary", "",
       "> Subject: Startup Policies | Deliverable: customer research | Data: **SIMULATED** (generated by `navya/tools/simulate_survey_and_usability.py`, seed 2026, not collected from real people) | Mentor approval for simulated data: 2026-11-24", "",
       f"Respondents: {len(rows)} students aged {min(r['age'] for r in rows)} to {max(r['age'] for r in rows)} in {len(set(r['city'] for r in rows))} cities. Raw rows: `survey-responses.csv`.", "",
       "| Question | Result |", "|---|---|",
       f"| Sold something second-hand online before | {count('sold_online_before','Yes')} ({pct(count('sold_online_before','Yes'))}) |",
       f"| Bought second-hand before | {count('bought_secondhand_before','Yes')} ({pct(count('bought_secondhand_before','Yes'))}) |",
       f"| Interest in a campus-friendly resale app, 1 to 5 | mean {st.mean(r['interest_1to5'] for r in rows):.2f}, {sum(1 for r in rows if r['interest_1to5']>=4)} gave 4 or 5 |",
       f"| Safety worry when meeting a stranger, 1 to 5 | mean {st.mean(r['safety_concern_1to5'] for r in rows):.2f} |",
       f"| Would pay to pin a listing | Yes {count('would_pay_to_boost','Yes')}, Maybe {count('would_pay_to_boost','Maybe')}, No {count('would_pay_to_boost','No')} |",
       f"| Highest fee they named (Yes and Maybe only) | median Rs {st.median(pay):.0f}, mean Rs {st.mean(pay):.0f} |",
       f"| Items they could list now | median {st.median(r['items_to_sell'] for r in rows):.0f}, total {sum(r['items_to_sell'] for r in rows)} |", "",
       "Biggest problem with current options:", "", "| Problem | Respondents |", "|---|---|"]
for p in PROBLEMS:
    out.append(f"| {p} | {count('biggest_problem', p)} |")
out += ["", "Main platform used:", "", "| Platform | Respondents |", "|---|---|"]
for p in PLATFORMS:
    out.append(f"| {p} | {count('main_platform', p)} |")
out += ["", "What this does and does not show: the sample is invented, so it can only show that the survey questions produce usable numbers. It does not show demand.", ""]
open(OUT / "survey-summary.md", "w").write("\n".join(out))

# usability: 5 participants x 5 tasks. Seconds taken, whether they finished, and an error count.
TASKS = [("Find a denim jacket under Rs 1,000", 25, 0.98), ("Sign up and post a listing with a photo", 140, 0.92), ("Message a seller", 30, 0.96),
         ("Boost a listing (test card)", 55, 0.9), ("Mark your own listing as sold", 20, 0.98)]
res = []
for pid in range(1, 6):
    for name, base, ok in TASKS:
        t = max(8, round(rnd.gauss(base, base * 0.3)))
        done = rnd.random() < ok
        res.append((pid, name, t, done, 0 if done and rnd.random() < 0.7 else rnd.choice([1, 1, 2])))
u = ["# Usability results", "",
     "> Subject: Software Testing | Deliverable: usability check with users | Data: **SIMULATED** (same generator, seed 2026).", "",
     "Method: each participant did 5 tasks on a phone-sized screen, thinking aloud. Time in seconds, finished or not, and the number of wrong taps or dead ends.", "",
     "| Task | Finished | Median time (s) | Wrong taps (total) |", "|---|---|---|---|"]
for name, base, ok in TASKS:
    rs = [r for r in res if r[1] == name]
    u.append(f"| {name} | {sum(1 for r in rs if r[3])}/5 | {st.median(r[2] for r in rs):.0f} | {sum(r[4] for r in rs)} |")
# System Usability Scale: 10 statements answered 1 to 5, odd ones positive, even ones negative, score 0 to 100
def sus(good):
    a = []
    for i in range(10):
        pos = i % 2 == 0
        base = 4.2 if good else 3.0
        v = min(5, max(1, round(rnd.gauss(base if pos else 6 - base, 0.8))))
        a.append((v - 1) if pos else (5 - v))
    return sum(a) * 2.5
scores = [sus(rnd.random() < 0.8) for _ in range(5)]
tot = sum(1 for r in res if r[3])
u += ["", f"Overall task completion: {tot}/25 ({100*tot//25}%).", "",
      f"System Usability Scale per participant: {', '.join(f'{x:.1f}' for x in scores)}. Mean {st.mean(scores):.1f}. The published average is about 68 (see `real-world-benchmarks.md`). With 5 people the interval is wide, so this shows nothing about real users.", "",
      "Findings written before the data existed, to be confirmed or removed after a real session (they come from our own use of the app):", "",
      "- The 'Featured' badge sat on top of the save heart on the card. Fixed (DEF-004).",
      "- The list shows the previous results for a moment while the new ones load. Not fixed, listed as an open issue.",
      "- The sign-up form asks for a city. It is used to fill the city on listings, so it stays.", ""]
open(OUT / "usability-results.md", "w").write("\n".join(u))
print("wrote survey-responses.csv, survey-summary.md, usability-results.md")
